# shellcheck shell=bash
# Snapshots of the unrebuildable volumes: `backup` and `restore`.
# Sourced by bin/amphoractl, never run on its own.

# ------------------------------------------------------------------ backup --
# The only part of this stack that `up` cannot rebuild is the named volumes, and they
# exist in exactly one place: inside the podman machine VM. `podman machine reset` or
# `rm` — a plausible step during a Podman Desktop upgrade — destroys every session,
# memory, skill and kanban card without the `nuke` prompt ever appearing. Hence this.
#
# Only two volumes are worth saving. amphora-dind-storage is an image cache,
# amphora-dind-certs is regenerated by dind on every `up`, and amphora-searxng-config is seeded
# from etc/searxng. Those three come back on their own.
BACKUP_VOLS="$VOL_DATA $VOL_SIGNAL"

# Plain tarballs on the Mac's own disk: FileVault covers them at rest, Time Machine
# picks them up, and they sit above the projects/ mount root so the agent cannot see
# them. Gitignored — a snapshot of /opt/data is a full copy of the agent's memory.
BACKUP_DIR="${AMPHORA_BACKUP_DIR:-$RUNTIME_DIR/backups}"
BACKUP_KEEP="${AMPHORA_BACKUP_KEEP:-14}"

# Paths inside a volume that are caches or re-downloadable packages, not state. Without
# these a snapshot of hermes-data is 1.8 GB uncompressed, of which about 150 MB is the
# part you would grieve over: state.db, skills, memories, kanban, cron, sessions, SOUL.md.
# The rest is uv's cache, HuggingFace's cache, npm's cache and npx installs under
# home/.npm, Hermes' lazily-installed python packages, the toolchains under .local/share
# and the web_extract cache, plus ./bin (uv, uvx, tirith, the browser-use wrappers) — all
# of which the agent refetches on demand, given network.
#
# This is a denylist of caches rather than an allowlist of state on purpose. Hermes will
# grow new state directories in versions we have not seen; an allowlist would drop them
# silently, whereas a denylist that falls behind only makes the archive bigger. If you
# add a path here, be certain the agent can rebuild it without you.
BACKUP_EXCLUDE="${AMPHORA_BACKUP_EXCLUDE:-./home/.cache ./home/.npm ./.cache ./lazy-packages ./.local/share ./.cua-driver/packages ./bin ./skills/.hub/index-cache ./cache/web}"

# Excludes are a property of ONE volume, never of backups in general. Both volumes have a
# ./.local/share: in hermes-data it is uv and tirith toolchains, and in amphora-signal-data
# it is signal-cli's account database and identity keys — the single thing in this stack
# that cannot be rebuilt from anywhere. Applying the list to every volume produced a
# Signal snapshot containing two empty directories and nothing else, and it looked like a
# success. A volume with no entry here is copied whole; that is the safe default and new
# volumes must keep it.
backup_excludes_for() {
  case "$1" in
    "$VOL_DATA") printf '%s' "$BACKUP_EXCLUDE" ;;
    *)           printf '' ;;
  esac
}
# The archive holding one volume inside one snapshot directory. Snapshots taken before
# the rename to Amphora name the Signal volume by its old name; hermes-data kept its
# name, so it needs no mapping. Echoes the path; 1 if the snapshot has neither.
snapshot_archive() {
  local dir="$1" vol="$2"
  if [ -f "$dir/$vol.tgz" ]; then printf '%s' "$dir/$vol.tgz"; return 0; fi
  case "$vol" in
    "$VOL_SIGNAL")
      if [ -f "$dir/hermes-signal-data.tgz" ]; then
        printf '%s' "$dir/hermes-signal-data.tgz"; return 0
      fi ;;
  esac
  return 1
}

LAUNCHD_LABEL="local.amphora.backup"
LAUNCHD_PLIST="$HOME/Library/LaunchAgents/$LAUNCHD_LABEL.plist"

# A snapshot is a byte-for-byte copy of everything the agent has ever been told. The
# repo's root .gitignore covers backups/, but that entry is one careless edit from being
# gone, and the failure is silent and unrecoverable — history keeps what it is given.
# So the directory also ignores itself, wherever it is: belt, braces, and a third strap.
backup_guard_gitignore() {
  local ign="$BACKUP_DIR/.gitignore"
  if [ -f "$ign" ]; then return 0; fi
  cat > "$ign" <<'IGN'
# Written by `amphoractl backup`, and deliberately self-contained.
#
# These snapshots are full copies of /opt/data: every session, memory, skill and kanban
# card the agent holds. They must never reach git — not this repo, not any other. This
# file makes the directory ignore its own contents even if the `backups/` entry in the
# repo's root .gitignore is ever lost. Do not delete it.
*
IGN
  return 0
}

# tar runs inside a throwaway container, so nothing has to be installed on the Mac and
# no assumption is made about the volume's internal layout. The archive is lifted out
# with `podman cp` rather than through a host bind mount: a bind is written by the
# container's root and lands on the Mac owned by whatever the VM's uid mapping produces.
# $IMG_DIND is used only because it is already pulled and has busybox tar; its
# entrypoint is overridden so no engine starts.
#
# `--security-opt label=disable` is load-bearing and not a shortcut. The machine VM runs
# SELinux enforcing, and a file in a named volume carries the MCS category pair of the
# container that created it — `container_file_t:s0:c421,c907` for anything Hermes wrote
# at its pinned level. A second container gets its own pair, fails the MCS dominance
# check and is refused on every read, as root, on 0755 directories, with no capability
# able to override it. That is what a bare `tar` sees: `Permission denied` on
# everything, and no clue why.
# The helper is read-only and has no network, which is the trade for that.
#
# Restore needs no relabel afterwards. The helper runs without label separation, at
# plain s0, so what it extracts is categoryless and readable by Hermes at any level.
# That is the only reason: podman does NOT relabel a named volume on mount (see
# MCS_HERMES in settings.sh).
snapshot_volume() {
  local vol="$1" out="$2" helper="amphora-backup-tmp" err="" ex="" p tarcmd
  # Two patterns per path: busybox tar matches each stored name against the pattern
  # individually and does not prune a subtree from the directory entry alone.
  for p in $(backup_excludes_for "$vol"); do
    ex="$ex --exclude='$p' --exclude='$p/*'"
  done
  tarcmd="tar czf /tmp/vol.tgz$ex -C /data ."
  podman rm -f "$helper" >/dev/null 2>&1 || true
  # Both steps report what actually went wrong. A snapshot that fails quietly is worse
  # than no snapshot at all: it looks like a working backup until the day it matters.
  if ! err="$(podman run --name "$helper" --entrypoint sh \
       --security-opt label=disable \
       --network none --tmpfs /var/lib/docker \
       -v "$vol:/data:ro" "$IMG_DIND" \
       -c "$tarcmd" 2>&1)"; then
    c_red "  $vol — tar failed"
    if [ -n "$err" ]; then printf '%s\n' "$err" | sed 's/^/    /'; fi
    podman rm -f "$helper" >/dev/null 2>&1 || true
    return 1
  fi
  if ! err="$(podman cp "$helper:/tmp/vol.tgz" "$out" 2>&1)"; then
    c_red "  $vol — could not copy the archive out"
    if [ -n "$err" ]; then printf '%s\n' "$err" | sed 's/^/    /'; fi
    podman rm -f "$helper" >/dev/null 2>&1 || true
    return 1
  fi
  podman rm -f "$helper" >/dev/null 2>&1 || true
}

# created, not run: the archive has to be copied in before anything executes.
restore_volume() {
  local vol="$1" src="$2" helper="amphora-restore-tmp" rc=0
  podman volume exists "$vol" 2>/dev/null || podman volume create "$vol" >/dev/null
  podman rm -f "$helper" >/dev/null 2>&1 || true
  podman create --name "$helper" --entrypoint sh \
    --security-opt label=disable \
    --network none --tmpfs /var/lib/docker \
    -v "$vol:/data" "$IMG_DIND" \
    -c 'cd /data && rm -rf -- ..?* .[!.]* * 2>/dev/null; tar xzf /tmp/vol.tgz -C /data' >/dev/null
  if podman cp "$src" "$helper:/tmp/vol.tgz" >/dev/null 2>&1; then
    podman start -a "$helper" >/dev/null 2>&1 || rc=1
  else
    rc=1
  fi
  podman rm -f "$helper" >/dev/null 2>&1 || true
  return "$rc"
}

# An archive that suddenly collapses is the signature of an exclude pattern matching more
# than it was meant to, and it reports success on the way past. Compare against the
# previous snapshot of the same volume and say so. A warning, not a failure: a volume
# genuinely can shrink, and refusing to write the backup would be the wrong response to
# a suspicion.
backup_size_check() {
  local vol="$1" dest="$2" prev now was
  # $dest was just created and sorts last, so the previous snapshot is the one before it.
  prev="$(ls -1d "$BACKUP_DIR"/[0-9]* 2>/dev/null | sort | tail -2 | head -1 || true)"
  [ -n "$prev" ] || return 0
  [ "$prev" != "$dest" ] || return 0
  local pa
  pa="$(snapshot_archive "$prev" "$vol")" || return 0
  now="$(file_size "$dest/$vol.tgz")"
  was="$(file_size "$pa")"
  case "$now$was" in ''|*[!0-9]*) return 0 ;; esac
  [ "$was" -gt 0 ] || return 0
  if [ "$now" -lt $((was / 2)) ]; then
    c_ylw "    shrank from $((was / 1024))K to $((now / 1024))K since $(basename "$prev")"
    info "  check the exclude list actually means what it says for this volume"
  fi
  return 0
}

# Set to the stamp of a snapshot `cmd_backup run` completed; empty when it skipped.
LAST_SNAPSHOT=""

cmd_backup() {
  need_podman
  local sub="${1:-run}"
  shift || true
  case "$sub" in

    run)
      # A nightly launchd job on a Mac whose podman machine happens to be stopped is not
      # a failure worth an error every morning.
      machine_running || { c_ylw "podman machine not running — backup skipped"; return 0; }
      mkdir -p "$BACKUP_DIR"
      backup_guard_gitignore
      local stamp dest v rc=0 stopped="" total cut keep
      stamp="$(date +%Y%m%d-%H%M%S)"
      dest="$BACKUP_DIR/$stamp"
      mkdir -p "$dest"

      # Quiesce. Hermes' state is SQLite; a tar taken mid-write can contain a torn
      # database that only announces itself at restore time, which is the worst possible
      # moment. A few seconds of downtime is the cheaper half of that trade.
      for v in "$C_HERMES" "$C_SIGNAL"; do
        if running "$v"; then
          podman stop -t 20 "$v" >/dev/null 2>&1 || true
          stopped="$stopped $v"
        fi
      done

      echo "snapshot $stamp"
      for v in $BACKUP_VOLS; do
        if podman volume exists "$v" 2>/dev/null; then
          if snapshot_volume "$v" "$dest/$v.tgz"; then
            info "$v  $(du -h "$dest/$v.tgz" | awk '{print $1}')"
            backup_size_check "$v" "$dest"
          else
            rc=1
          fi
        fi
      done

      # Restart before reporting failure: leaving the stack down is worse than a bad backup.
      for v in $stopped; do
        podman start "$v" >/dev/null 2>&1 || c_ylw "  could not restart $v"
      done

      if [ "$rc" -ne 0 ]; then
        rm -rf "$dest"
        die "backup failed — nothing written"
      fi

      {
        echo "amphoractl snapshot $stamp"
        echo "stack   $STACK_DIR"
        echo "image   $IMG_HERMES"
        echo "volumes $(cd "$dest" && ls -1 ./*.tgz | sed 's|^\./||' | tr '\n' ' ')"
        echo "excluded $VOL_DATA: $BACKUP_EXCLUDE"
        echo "excluded (other volumes): none"
      } > "$dest/MANIFEST"
      LAST_SNAPSHOT="$stamp"

      # Rotation. `head -n -N` is a GNU-ism; BSD head has no negative count.
      # The snapshot `rollback --data` would restore is spared, however old it is.
      keep="$(rollback_snapshot || true)"
      total="$(ls -1d "$BACKUP_DIR"/[0-9]* 2>/dev/null | wc -l | tr -d ' ')"
      if [ "$total" -gt "$BACKUP_KEEP" ]; then
        cut=0
        for v in $(ls -1 "$BACKUP_DIR" | grep '^[0-9]' | sort | sed -n "1,$((total - BACKUP_KEEP))p"); do
          if [ "$v" = "$keep" ]; then continue; fi
          rm -rf "${BACKUP_DIR:?}/$v"
          cut=$((cut + 1))
        done
        if [ "$cut" -gt 0 ]; then info "rotated out $cut older snapshot(s)"; fi
      fi
      c_grn "backed up to $dest" ;;

    ls)
      [ -d "$BACKUP_DIR" ] || { info "no snapshots yet — amphoractl backup"; return 0; }
      local d found=0
      for d in "$BACKUP_DIR"/[0-9]*; do
        [ -d "$d" ] || continue
        found=1
        printf '  %-18s %s\n' "$(basename "$d")" "$(du -sh "$d" | awk '{print $1}')"
      done
      [ "$found" = "1" ] || info "no snapshots yet — amphoractl backup" ;;

    # A LaunchAgent rather than cron: it fires on wake if the Mac was asleep at the
    # scheduled time, which cron does not. Generated here, never committed — the plist
    # necessarily carries this machine's paths.
    schedule)
      case "${1:-on}" in
        on)
          local podman_bin
          podman_bin="$(dirname "$(command -v podman)")"
          mkdir -p "$HOME/Library/LaunchAgents" "$BACKUP_DIR"
          cat > "$LAUNCHD_PLIST" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LAUNCHD_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$STACK_DIR/bin/amphoractl</string>
    <string>backup</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>$podman_bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Hour</key><integer>3</integer>
    <key>Minute</key><integer>30</integer>
  </dict>
  <key>StandardOutPath</key><string>$BACKUP_DIR/backup.log</string>
  <key>StandardErrorPath</key><string>$BACKUP_DIR/backup.log</string>
</dict>
</plist>
PLIST
          launchctl unload "$LAUNCHD_PLIST" >/dev/null 2>&1 || true
          launchctl load "$LAUNCHD_PLIST"
          c_grn "nightly snapshot scheduled for 03:30"
          info "plist  $LAUNCHD_PLIST"
          info "log    $BACKUP_DIR/backup.log" ;;
        off)
          launchctl unload "$LAUNCHD_PLIST" >/dev/null 2>&1 || true
          rm -f "$LAUNCHD_PLIST"
          c_grn "nightly snapshot unscheduled" ;;
        status)
          if [ -f "$LAUNCHD_PLIST" ]; then
            c_grn "installed: $LAUNCHD_PLIST"
            launchctl list "$LAUNCHD_LABEL" >/dev/null 2>&1 \
              && c_grn "  loaded" || c_ylw "  not loaded — amphoractl backup schedule on"
          else
            c_ylw "not scheduled — amphoractl backup schedule on"
          fi ;;
        *) die "usage: amphoractl backup schedule [on|off|status]" ;;
      esac ;;

    *) die "usage: amphoractl backup [run|ls|schedule]" ;;
  esac
}

# No prompt: callers have asked. $2 is the list of volumes the snapshot holds.
restore_snapshot() {
  local dir="$1" found="$2" v rc=0
  # Removed, not stopped: `up` recreates them, and a container holding the volume open
  # while it is emptied is asking for trouble.
  podman rm -f "$C_HERMES" >/dev/null 2>&1 || true
  podman rm -f "$C_SIGNAL" >/dev/null 2>&1 || true
  # dind holds subpath mounts of the data volume, which pin the directories they found;
  # a restore replaces them, so dind has to be recreated as well.
  podman rm -f "$C_DIND" >/dev/null 2>&1 || true
  for v in $found; do
    if restore_volume "$v" "$(snapshot_archive "$dir" "$v")"; then
      c_grn "  $v restored"
    else
      c_red "  $v — restore failed"
      rc=1
    fi
  done
  return "$rc"
}

cmd_restore() {
  need_podman
  local dir="${1:-}" v found="" a
  if [ -z "$dir" ]; then
    dir="$(ls -1d "$BACKUP_DIR"/[0-9]* 2>/dev/null | sort | tail -1 || true)"
  elif [ ! -d "$dir" ] && [ -d "$BACKUP_DIR/$dir" ]; then
    dir="$BACKUP_DIR/$dir"
  fi
  [ -n "$dir" ] && [ -d "$dir" ] || die "no snapshot to restore — amphoractl backup ls"

  for v in $BACKUP_VOLS; do
    if snapshot_archive "$dir" "$v" >/dev/null; then found="$found $v"; fi
  done
  [ -n "$found" ] || die "no volume archives in $dir"

  c_ylw "Restoring $(basename "$dir") replaces the entire current contents of:$found"
  info "Everything Hermes has learned since that snapshot is discarded."
  read -r -p "Continue? [y/N] " a
  [ "$a" = "y" ] || { echo "aborted"; return 0; }

  restore_snapshot "$dir" "$found" || die "restore incomplete — see above; run it again before 'up'"
  c_grn "restored"
  info "next: amphoractl up"
}
